#!/usr/bin/env node
/**
 * Render one sample per built-in palette into examples/, plus a README gallery.
 * Usage: npm run examples   (builds first; this script imports from dist/)
 *
 * Samples are half size (600×750, ~30 KB each). The composition is identical to
 * the default 1200×1500 output because noise coordinates are normalized to the
 * image size, so these are faithful previews at a quarter of the bytes.
 */

import { mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { colorPalettes, createMeshGradients, findPalette, paletteAccent } from '../dist/index.js';
import { examplesDir, featuredDir, featuredImage, readFeatured, repoRoot } from './featured.mjs';

const COLUMNS = 4;

/**
 * Each palette gets its own seed, so the gallery shows varied compositions
 * instead of 56 copies of one layout. The seed is the palette name rather than
 * a fresh random string: a rerun then reproduces the same gallery, so `npm run
 * examples` doesn't rewrite every image (2 MB of diff) each time it is run.
 * Pass --seed <string> to render the whole set with one shared seed instead,
 * which is the layout-comparison view.
 */
const sharedSeedIndex = process.argv.indexOf('--seed');
const sharedSeed = sharedSeedIndex === -1 ? undefined : process.argv[sharedSeedIndex + 1];
const seedFor = (palette) => sharedSeed ?? palette.name;

const gradients = createMeshGradients({ palettes: colorPalettes, width: 700, height: 800 });

mkdirSync(examplesDir, { recursive: true });
// Clear old samples so renamed or removed palettes don't leave stale images behind.
for (const file of readdirSync(examplesDir)) {
  if (file.endsWith('.webp')) rmSync(join(examplesDir, file));
}

let totalBytes = 0;
for (const palette of colorPalettes) {
  const { buffer } = await gradients.generate({ seed: seedFor(palette), palette: palette.name });
  writeFileSync(join(examplesDir, `${palette.name}.webp`), buffer);
  totalBytes += buffer.length;
  console.log(`✓ ${palette.name}.webp (${(buffer.length / 1024).toFixed(1)} KB)`);
}

const cells = colorPalettes.map(
  (palette) =>
    `<td align="center"><img src="./${palette.name}.webp" width="180" alt="${palette.name}"><br>` +
    `<code>${palette.name}</code><br><sub>${palette.colors.join(' ')}</sub><br>` +
    `<sub>accent ${paletteAccent(palette)} · seed <code>${seedFor(palette)}</code></sub></td>`,
);
const rows = [];
for (let i = 0; i < cells.length; i += COLUMNS) {
  rows.push(`  <tr>\n    ${cells.slice(i, i + COLUMNS).join('\n    ')}\n  </tr>`);
}

writeFileSync(
  join(examplesDir, 'README.md'),
  `<!-- AUTO-GENERATED by scripts/generate-examples.mjs. Run \`npm run examples\` to refresh. -->
# Palette examples

One sample per built-in palette, 600×750 WebP. ${
    sharedSeed
      ? `All rendered with seed \`${sharedSeed}\`, so the composition is identical and only the colors differ.`
      : 'Each one uses its own palette name as the seed, so the compositions vary; the seed is listed under each sample.'
  }

<table>
${rows.join('\n')}
</table>
`,
);

// ── Featured: the hand-picked pairs shown in the root README ─────────────────
const featured = readFeatured();
mkdirSync(featuredDir, { recursive: true });
for (const file of readdirSync(featuredDir)) {
  if (file.endsWith('.webp')) rmSync(join(featuredDir, file));
}

for (const entry of featured) {
  findPalette(entry.palette); // fails loudly on a typo in featured.json
  const { buffer } = await gradients.generate({ seed: entry.seed, palette: entry.palette });
  writeFileSync(join(repoRoot, featuredImage(entry)), buffer);
  totalBytes += buffer.length;
  console.log(`✓ ${featuredImage(entry)} (${(buffer.length / 1024).toFixed(1)} KB)`);
}

console.log(
  `Done: ${colorPalettes.length} samples + ${featured.length} featured, ` +
    `${(totalBytes / 1024).toFixed(0)} KB total → examples/`,
);
